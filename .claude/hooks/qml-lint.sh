#!/usr/bin/env bash
# Edit-time qmllint for the Quickshell bar (called by post-edit-check.sh with
# the path of the .qml file that was just edited).
#
# Why it exists: `qs -p` (quickshell_check) only proves the QML *loads*. A
# misspelled singleton member (`Theme.subtxt`) or property name is not a load
# error — it evaluates to undefined at runtime and the bar just looks wrong.
# qmllint resolves those statically, in well under a second, with no bar
# restart.
#
# How it stays quiet: qmllint does not understand everything Quickshell does
# (PanelWindow, GlobalShortcut, anchor groups…), so a clean tree still carries
# a couple of hundred false positives. Rather than maintain a suppress list,
# this lints the file twice — as edited, and as it is at HEAD — and reports
# only findings the edit introduced.
#
# Fails open everywhere: no qs, no qmllint in its closure, no deployed config
# (CI, a fresh host) all exit 0 silently. Exit 2 = new findings on stderr.
file=$1
[ -f "$file" ] || exit 0
src=$(dirname "$file")
name=$(basename "$file")

# qmllint and every QML import path come from the running Quickshell's own
# closure: nothing extra to install, and the type info always matches the
# Quickshell/Qt that will actually load the file.
qs_bin=$(command -v qs 2>/dev/null) || exit 0
qs_root=$(readlink -f "$qs_bin")
qs_root=${qs_root%/bin/qs}
lint=""
imports=()
while read -r p; do
  [ -z "$lint" ] && [ -x "$p/bin/qmllint" ] && lint="$p/bin/qmllint"
  [ -d "$p/lib/qt-6/qml" ] && imports+=(-I "$p/lib/qt-6/qml")
done < <(nix-store -qR "$qs_root" 2>/dev/null)
[ -n "$lint" ] || exit 0

# Theme.qml, Motion.qml and friends are generated by home/hyprland.nix, so
# they only exist in the deployed config. Overlay the worktree's QML onto a
# copy of it — the same trick quickshell_check uses.
deployed=${XDG_CONFIG_HOME:-$HOME/.config}/quickshell
[ -f "$deployed/shell.qml" ] || exit 0
tmp=$(mktemp -d) || exit 0
trap 'rm -rf "$tmp"' EXIT
cp -L "$deployed"/*.qml "$tmp"/ 2>/dev/null
# Deployed files are read-only store copies; without this the overlay below
# cannot overwrite them and the lint would silently check the deployed QML.
chmod -R u+w "$tmp"
cp -L "$src"/*.qml "$tmp"/ || exit 0

# Quickshell treats `pragma Singleton` as enough; qmllint wants a qmldir
# entry before it will resolve members on the singleton.
(
  cd "$tmp" || exit 0
  grep -l '^pragma Singleton' ./*.qml 2>/dev/null | while read -r f; do
    f=${f#./}
    echo "singleton ${f%.qml} 1.0 $f"
  done >qmldir
)

# One finding per line, line:col stripped so an edit that merely shifts code
# does not make old findings look new. "Unqualified access" is disabled: it
# is a style rule this codebase does not follow.
run_lint() {
  (cd "$tmp" && "$lint" "${imports[@]}" --unqualified disable "$name" 2>&1) |
    grep -E '^(Warning|Error)' |
    grep -v 'not declared as singleton in qmldir'
}
strip_pos() { sed -E 's/:[0-9]+:[0-9]+:/:/' | sort; }

run_lint >"$tmp/.new.full"
strip_pos <"$tmp/.new.full" >"$tmp/.new"

if git -C "$src" show "HEAD:./$name" >"$tmp/.head.qml" 2>/dev/null; then
  cp "$tmp/$name" "$tmp/.edited.qml"
  cp "$tmp/.head.qml" "$tmp/$name"
  run_lint | strip_pos >"$tmp/.base"
  cp "$tmp/.edited.qml" "$tmp/$name"
else
  : >"$tmp/.base" # new file: every finding is new
fi

fresh=$(comm -13 "$tmp/.base" "$tmp/.new")
[ -z "$fresh" ] && exit 0

{
  echo "qmllint: this edit introduced new findings in $name (not present at HEAD)."
  echo "A misspelled Theme/Motion member or property is undefined at runtime and"
  echo "quickshell_check will not catch it. qmllint has blind spots for some"
  echo "Quickshell types, so judge each one — fix it or say why it is a false positive:"
  # Show the findings with their line numbers restored.
  while IFS= read -r line; do
    grep -F -- "${line#*: "$name": }" "$tmp/.new.full" | head -3
  done <<<"$fresh" | sort -u
} >&2
exit 2
